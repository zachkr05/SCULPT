"""Step 1: pretrain on scene_generator.gen_sample()['original_trajectory'].

Save this file as SCULPT/baseline/train.py, beside baseline/diffusion.py.
Requires Python >= 3.10, PyTorch >= 2.3, numpy, scipy, and matplotlib.

From the SCULPT directory:
    python baseline/train.py
    python baseline/train.py --batch-size 8 --workers 4 --steps 100000
    python baseline/train.py --resume runs/pretrain/latest.pt

Every model call uses conditioning=None: scene inputs and diffusion noise
levels are used, but no user/preference conditioning or edited paths are used.
Clean xy is normalized to [-1, 1], corrupted with a cosine DDPM schedule,
and supervised with epsilon-prediction MSE. Fresh procedural scenes are
generated by CPU workers; a separate fixed validation set is kept in memory.
Invalid/missing, out-of-bounds, or colliding B-spline targets are resampled.

Outputs (default: SCULPT/runs/pretrain):
    pretrained.pt    Best validation EMA weights, as a plain model state_dict.
    latest.pt        Resumable model/EMA/optimizer/scaler/RNG checkpoint.
    config.json      Model settings, normalization, and diffusion settings.
    metrics.csv      Training and validation noise MSE.
    samples_*.png    Reference and generated paths on held-out scenes.
    samples_*.npz    The same reference/generated xy in original grid units.

For subsequent fine-tuning, instantiate the same architecture using the
model_config in config.json and call:
    model.load_state_dict(torch.load('runs/pretrain/pretrained.pt',
                                     map_location='cpu', weights_only=True))

Previews use deterministic DDIM sampling (eta=0), starting from noise without
access to the reference path. Endpoints are inpainted at the correct noise
level. Your A* implementation floors start/goal coordinates, so preview
endpoints use floor(robot_pos)/floor(goal_pos), matching the demonstrations.

Diffusion references:
    https://arxiv.org/abs/2102.09672 (cosine schedule)
    https://arxiv.org/abs/2010.02502 (DDIM sampling)
"""

