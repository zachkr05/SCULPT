SCENE_KEYS = ("occupancy_grid", "esdf", "semantic_map", "robot_pos", "goal_pos")
GRID_SIZE = (128, 128)
HORIZON = 300


class ProceduralScenes(Dataset):
    """Index-seeded scenes: disjoint train/validation streams and resumable data."""

    def __init__(self, size: int, seed: int, split: int, start: int = 0):
        self.size, self.seed, self.split, self.start = size, seed, split, start

    def __len__(self) -> int:
        return self.size

    def __getitem__(self, index: int) -> dict:
        seed_words = np.random.SeedSequence(
            [self.seed, self.split, self.start + index]
        ).generate_state(4)
        np.random.seed(seed_words)
        random.seed(int(seed_words[0]))
        last_error = None
        for _ in range(50):
            try:
                sample = gen_sample(debug=False)
            except (ValueError, FloatingPointError) as error:
                # For example, a degenerate spline; do not hide import/key errors.
                last_error = error
                continue
            if sample is None:
                continue
            path = np.asarray(sample["original_trajectory"], dtype=np.float32)
            if path.shape != (HORIZON, 2) or not np.isfinite(path).all():
                continue
            if (path < 0).any() or (path > np.array(GRID_SIZE) - 1).any():
                continue
            occupancy = np.asarray(sample["occupancy_grid"])
            if occupancy.shape != GRID_SIZE:
                raise ValueError(f"Expected occupancy grid shape {GRID_SIZE}")
            # Sample segments at <= 0.25 grid-cell spacing, checking the spline
            # rather than assuming that its collision-free A* control path suffices.
            collision = False
            for first, second in zip(path[:-1], path[1:]):
                count = max(2, int(np.ceil(np.linalg.norm(second - first) / .25)) + 1)
                cells = np.rint(np.linspace(first, second, count)).astype(np.int64)
                if occupancy[cells[:, 0], cells[:, 1]].any():
                    collision = True
                    break
            if collision:
                continue
            if not np.isfinite(sample["esdf"]).all():
                continue
            return sample
        raise RuntimeError(f"Could not generate a valid scene for index {index}") from last_error


def collate_scenes(samples: list[dict]) -> tuple[dict[str, Tensor], Tensor]:
    scene = {
        key: torch.from_numpy(np.stack([sample[key] for sample in samples]))
        for key in SCENE_KEYS
    }
    scene["occupancy_grid"] = scene["occupancy_grid"].to(torch.uint8)
    scene["semantic_map"] = scene["semantic_map"].long()
    for key in ("esdf", "robot_pos", "goal_pos"):
        scene[key] = scene[key].float()
    scene["obstacle_metadata"] = pack_obstacles([
        sample["obstacle_metadata"] for sample in samples
    ])
    clean = torch.from_numpy(np.stack([
        sample["original_trajectory"] for sample in samples
    ])).float()
    scale = torch.tensor(GRID_SIZE, dtype=torch.float32) - 1
    return scene, 2.0 * clean / scale - 1.0


def make_loader(dataset: Dataset, args, device: torch.device) -> DataLoader:
    options = dict(
        batch_size=args.batch_size, num_workers=args.workers,
        collate_fn=collate_scenes, shuffle=False, pin_memory=device.type == "cuda",
        # DataLoader bookkeeping must not consume the model/noise RNG stream.
        generator=torch.Generator().manual_seed(args.seed),
    )
    if args.workers:
        options.update(multiprocessing_context="spawn", prefetch_factor=2)
    return DataLoader(dataset, **options)


def to_device(batch, device: torch.device):
    scene, clean = batch
    return ({key: value.to(device, non_blocking=True) for key, value in scene.items()},
            clean.to(device, non_blocking=True))


class DiffusionSchedule:
    def __init__(self, steps: int, device: torch.device):
        self.steps = steps
        t = torch.linspace(0, steps, steps + 1, dtype=torch.float64)
        alpha_bar = torch.cos(((t / steps + .008) / 1.008) * math.pi / 2).square()
        alpha_bar = alpha_bar / alpha_bar[0]
        self.betas = (1 - alpha_bar[1:] / alpha_bar[:-1]).clamp(1e-8, .999).float().to(device)
        self.alpha_bar = (1 - self.betas).cumprod(0)

    def corrupt(self, clean: Tensor, steps: Tensor, noise: Tensor) -> Tensor:
        alpha = self.alpha_bar[steps][:, None, None]
        return alpha.sqrt() * clean + (1 - alpha).sqrt() * noise

    @torch.no_grad()
    def sample(self, model: nn.Module, scene: dict[str, Tensor], sampling_steps: int,
               seed: int) -> Tensor:
        device = self.alpha_bar.device
        batch = scene["robot_pos"].shape[0]
        rng = torch.Generator(device=device).manual_seed(seed)
        x = torch.randn(batch, HORIZON, 2, device=device, generator=rng)
        endpoint_noise = x[:, [0, -1]].clone()
        scale = torch.tensor(GRID_SIZE, device=device) - 1
        endpoints = torch.stack([
            scene["robot_pos"].floor(), scene["goal_pos"].floor()
        ], dim=1)
        endpoints = 2.0 * endpoints / scale - 1.0
        times = torch.linspace(self.steps - 1, 0, sampling_steps).round().long().tolist()
        for index, step in enumerate(times):
            alpha = self.alpha_bar[step]
            x[:, [0, -1]] = alpha.sqrt() * endpoints + (1 - alpha).sqrt() * endpoint_noise
            epsilon = model(x, step, scene, conditioning=None)
            clean = ((x - (1 - alpha).sqrt() * epsilon) / alpha.sqrt()).clamp(-1, 1)
            # Recompute epsilon after clipping for a consistent DDIM update.
            epsilon = (x - alpha.sqrt() * clean) / (1 - alpha).sqrt()
            previous = self.alpha_bar[times[index + 1]] if index + 1 < len(times) else x.new_tensor(1.)
            x = previous.sqrt() * clean + (1 - previous).sqrt() * epsilon
        x[:, [0, -1]] = endpoints
        return (x + 1.0) * scale / 2.0


@torch.no_grad()
def update_ema(ema: nn.Module, model: nn.Module, step: int, decay: float) -> None:
    decay = min(decay, (1 + step) / (10 + step))
    for averaged, current in zip(ema.parameters(), model.parameters()):
        averaged.lerp_(current, 1 - decay)


@torch.no_grad()
def validate(model: nn.Module, batches: list, schedule: DiffusionSchedule,
             device: torch.device, seed: int) -> float:
    model.eval()
    rng = torch.Generator(device=device).manual_seed(seed)
    total, count = 0.0, 0
    for batch in batches:
        scene, clean = to_device(batch, device)
        # Identical validation noise and timesteps at every evaluation.
        steps = torch.randint(schedule.steps, (len(clean),), device=device, generator=rng)
        noise = torch.randn(clean.shape, device=device, generator=rng)
        predicted = model(schedule.corrupt(clean, steps, noise), steps, scene, conditioning=None)
        total += F.mse_loss(predicted.float(), noise, reduction="sum").item()
        count += noise.numel()
    return total / count


@torch.no_grad()
def save_preview(model, batch, schedule, args, device, step: int) -> None:
    import matplotlib.pyplot as plt

    scene, clean = to_device(batch, device)
    n = min(4, len(clean))
    scene = {key: value[:n] for key, value in scene.items()}
    predicted = schedule.sample(model, scene, args.sample_steps, args.seed + 2000000)
    reference = (clean[:n] + 1) * (torch.tensor(GRID_SIZE, device=device) - 1) / 2
    predicted, reference = predicted.cpu().numpy(), reference.cpu().numpy()
    occupancy = scene["occupancy_grid"].cpu().numpy()
    semantics = scene["semantic_map"].cpu().numpy()
    np.savez_compressed(args.output / f"samples_{step:07d}.npz",
                        predicted=predicted, reference=reference,
                        occupancy_grid=occupancy, semantic_map=semantics)
    figure, axes = plt.subplots(1, n, figsize=(5 * n, 5), squeeze=False)
    for index, ax in enumerate(axes[0]):
        ax.imshow(semantics[index].T, origin="lower", cmap="viridis", vmin=0, vmax=3)
        ax.plot(*reference[index].T, color="white", label="A* B-spline")
        ax.plot(*predicted[index].T, color="magenta", label="Generated")
        ax.scatter(*reference[index, 0], c="lime", marker="*", s=80, zorder=5)
        ax.scatter(*reference[index, -1], c="red", marker="X", s=60, zorder=5)
        ax.set(xlim=(0, 127), ylim=(0, 127), aspect="equal", title=f"Held-out scene {index + 1}")
        ax.legend(fontsize=8)
    figure.suptitle(f"Pretraining step {step} | no preference conditioning")
    figure.tight_layout()
    figure.savefig(args.output / f"samples_{step:07d}.png", dpi=140)
    plt.close(figure)


def atomic_save(value, path: Path) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    torch.save(value, temporary)
    temporary.replace(path)


def learning_rate(step: int, args) -> float:
    if step < args.warmup:
        return args.lr * (step + 1) / args.warmup
    progress = (step - args.warmup) / max(1, args.steps - args.warmup - 1)
    return args.lr * (.1 + .9 * .5 * (1 + math.cos(math.pi * min(1., progress))))


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--steps", type=int, default=100000, help="Total optimizer iterations")
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--workers", type=int, default=4, help="CPU scene-generation workers; 0 for debugging")
    parser.add_argument("--lr", type=float, default=1e-4)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--warmup", type=int, default=1000)
    parser.add_argument("--grad-clip", type=float, default=1.0)
    parser.add_argument("--ema-decay", type=float, default=.999)
    parser.add_argument("--diffusion-steps", type=int, default=1000)
    parser.add_argument("--sample-steps", type=int, default=50, help="DDIM preview steps")
    parser.add_argument("--eval-every", type=int, default=1000)
    parser.add_argument("--val-scenes", type=int, default=64)
    parser.add_argument("--log-every", type=int, default=100)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--dim", type=int, default=384)
    parser.add_argument("--depth", type=int, default=12)
    parser.add_argument("--heads", type=int, default=6)
    parser.add_argument("--device", default="auto", help="auto, cuda, cuda:0, or cpu")
    parser.add_argument("--no-amp", action="store_true", help="Disable CUDA mixed precision")
    parser.add_argument("--no-previews", action="store_true")
    parser.add_argument("--cpu-threads", type=int, default=4)
    parser.add_argument("--output", type=Path, default=PROJECT_ROOT / "runs" / "pretrain")
    parser.add_argument("--resume", type=Path)
    args = parser.parse_args()
    positive = (args.steps, args.batch_size, args.eval_every, args.val_scenes,
                args.log_every, args.cpu_threads, args.dim, args.depth, args.heads)
    if min(positive) < 1 or args.workers < 0 or args.warmup < 0 or args.seed < 0:
        parser.error("Counts must be positive; workers, warmup, and seed must be nonnegative")
    if not 2 <= args.sample_steps <= args.diffusion_steps:
        parser.error("Require 2 <= sample-steps <= diffusion-steps")
    if args.lr <= 0 or args.grad_clip <= 0 or args.weight_decay < 0 or not 0 <= args.ema_decay < 1:
        parser.error("Invalid learning rate, clipping, weight decay, or EMA decay")
    return args


def main() -> None:
    args = parse_args()
    device = torch.device(("cuda" if torch.cuda.is_available() else "cpu")
                          if args.device == "auto" else args.device)
    if device.type not in ("cuda", "cpu"):
        raise ValueError("This trainer supports CUDA and CPU devices")
    torch.set_num_threads(args.cpu_threads)
    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)
    if device.type == "cuda":
        torch.cuda.manual_seed_all(args.seed)
    model_config = dict(grid_size=GRID_SIZE, max_horizon=HORIZON, dim=args.dim,
                        depth=args.depth, heads=args.heads)
    model = TrajectoryDiffusionTransformer(**model_config).to(device)
    # Keep the unused preference branch fixed; fresh fine-tuning models default
    # to trainable parameters when these weights are loaded later.
    model.preference_embedding.requires_grad_(False)
    ema = copy.deepcopy(model).eval().requires_grad_(False)
    optimizer = torch.optim.AdamW(
        [p for p in model.parameters() if p.requires_grad], lr=args.lr,
        weight_decay=args.weight_decay,
    )
    amp = device.type == "cuda" and not args.no_amp
    amp_dtype = torch.bfloat16 if amp and torch.cuda.is_bf16_supported() else torch.float16
    scaler = torch.amp.GradScaler("cuda", enabled=amp and amp_dtype == torch.float16)
    schedule = DiffusionSchedule(args.diffusion_steps, device)
    start_step, best = 0, math.inf
    checkpoint = None
    if args.resume:
        checkpoint = torch.load(args.resume, map_location="cpu", weights_only=True)
        if checkpoint["model_config"] != model_config:
            raise ValueError("Resume with the same model dimensions/depth/heads")
        for key in ("seed", "batch_size", "diffusion_steps", "lr", "warmup", "ema_decay", "weight_decay"):
            if checkpoint["args"][key] != getattr(args, key):
                raise ValueError(f"Resume requires the original --{key.replace('_', '-')}")
        model.load_state_dict(checkpoint["model"])
        ema.load_state_dict(checkpoint["ema"])
        optimizer.load_state_dict(checkpoint["optimizer"])
        scaler.load_state_dict(checkpoint["scaler"])
        start_step, best = checkpoint["step"], checkpoint["best_validation"]
        if start_step >= args.steps:
            raise ValueError("--steps must exceed the checkpoint's completed step")
    args.output.mkdir(parents=True, exist_ok=True)
    if not args.resume and (args.output / "latest.pt").exists():
        raise FileExistsError("Output contains a checkpoint; use --resume or a new --output")
    if args.resume and not (args.output / "pretrained.pt").exists():
        # When resuming into a different output directory, select the best
        # weights among this directory's evaluations rather than referencing
        # a best-model file that only exists in the previous directory.
        best = math.inf
    serializable_args = {key: str(value) if isinstance(value, Path) else value
                         for key, value in vars(args).items()}
    (args.output / "config.json").write_text(json.dumps({
        "args": serializable_args, "model_config": model_config,
        "diffusion": {"steps": args.diffusion_steps, "schedule": "cosine", "s": .008,
                      "beta_max": .999, "prediction_type": "epsilon"},
        "normalization": "normalized_xy = 2 * xy / 127 - 1",
        "conditioning": None,
    }, indent=2) + "\n")
    print(f"Device: {device}; parameters: {sum(p.numel() for p in model.parameters()):,}", flush=True)
    print(f"Preparing {args.val_scenes} fixed validation scenes...", flush=True)
    validation = list(make_loader(ProceduralScenes(args.val_scenes, args.seed, split=1), args, device))
    remaining = (args.steps - start_step) * args.batch_size
    loader = make_loader(ProceduralScenes(remaining, args.seed, split=0,
                                         start=start_step * args.batch_size), args, device)
    if checkpoint:
        torch.set_rng_state(checkpoint["torch_rng"])
        if device.type == "cuda" and checkpoint["cuda_rng"]:
            torch.cuda.set_rng_state_all(checkpoint["cuda_rng"])
    del checkpoint
    metrics_path = args.output / "metrics.csv"
    new_csv = not metrics_path.exists() or metrics_path.stat().st_size == 0
    started, running, interval_count = time.monotonic(), 0.0, 0
    print("Pretraining on original trajectories; conditioning=None", flush=True)
    with metrics_path.open("a", newline="") as stream:
        writer = csv.writer(stream)
        if new_csv:
            writer.writerow(["step", "train_noise_mse", "validation_noise_mse", "learning_rate"])
        for step, batch in enumerate(loader, start=start_step + 1):
            model.train()
            scene, clean = to_device(batch, device)
            noise = torch.randn_like(clean)
            times = torch.randint(schedule.steps, (len(clean),), device=device)
            noisy = schedule.corrupt(clean, times, noise)
            rate = learning_rate(step - 1, args)
            for group in optimizer.param_groups:
                group["lr"] = rate
            optimizer.zero_grad(set_to_none=True)
            with torch.autocast(device_type=device.type, dtype=amp_dtype, enabled=amp):
                predicted = model(noisy, times, scene, conditioning=None)
                loss = F.mse_loss(predicted.float(), noise)
            if not torch.isfinite(loss):
                raise FloatingPointError(f"Non-finite loss at step {step}")
            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)
            nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip,
                                     error_if_nonfinite=not scaler.is_enabled())
            previous_scale = scaler.get_scale()
            scaler.step(optimizer)
            scaler.update()
            if scaler.get_scale() >= previous_scale:
                update_ema(ema, model, step, args.ema_decay)
            running += loss.item()
            interval_count += 1
            train_mse = running / interval_count
            if step % args.log_every == 0 or step == 1:
                elapsed = time.monotonic() - started
                print(f"step {step:7d}/{args.steps} | noise MSE {train_mse:.6f} | "
                      f"lr {rate:.2e} | {(step - start_step) / elapsed:.2f} steps/s", flush=True)
                writer.writerow([step, train_mse, "", rate])
                stream.flush()
                running, interval_count = 0.0, 0
            if step % args.eval_every == 0 or step == args.steps:
                validation_mse = validate(ema, validation, schedule, device, args.seed + 1000000)
                if not math.isfinite(validation_mse):
                    raise FloatingPointError("Non-finite validation loss")
                if validation_mse < best:
                    best = validation_mse
                    atomic_save(ema.state_dict(), args.output / "pretrained.pt")
                atomic_save({
                    "step": step, "model": model.state_dict(), "ema": ema.state_dict(),
                    "optimizer": optimizer.state_dict(), "scaler": scaler.state_dict(),
                    "best_validation": best, "model_config": model_config,
                    "args": serializable_args, "betas": schedule.betas.cpu(),
                    "torch_rng": torch.get_rng_state(),
                    "cuda_rng": torch.cuda.get_rng_state_all() if device.type == "cuda" else [],
                }, args.output / "latest.pt")
                writer.writerow([step, train_mse, validation_mse, rate])
                stream.flush()
                print(f"  validation noise MSE {validation_mse:.6f}; best {best:.6f}", flush=True)
                if not args.no_previews:
                    save_preview(ema, validation[0], schedule, args, device, step)
    print(f"Done. Best EMA weights: {args.output / 'pretrained.pt'}", flush=True)


if __name__ == "__main__":
    main()
